-- IF NOT EXISTS also permits explicitly baselining an existing Hibernate schema
-- at version 0. Existing rows are preserved; Hibernate validates the result.
CREATE TABLE IF NOT EXISTS applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL,
    job_title VARCHAR(255) NOT NULL,
    application_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL CHECK (status IN ('SENT', 'INTERVIEW', 'REJECTED', 'OFFER')),
    job_listing_url VARCHAR(255),
    notes TEXT
);
