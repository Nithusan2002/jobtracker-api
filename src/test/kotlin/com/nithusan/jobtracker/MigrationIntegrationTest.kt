package com.nithusan.jobtracker

import org.assertj.core.api.Assertions.assertThat
import org.assertj.core.api.Assertions.assertThatThrownBy
import org.flywaydb.core.Flyway
import org.junit.jupiter.api.Test
import org.testcontainers.containers.PostgreSQLContainer
import org.testcontainers.junit.jupiter.Container
import org.testcontainers.junit.jupiter.Testcontainers
import java.sql.DriverManager

@Testcontainers
class MigrationIntegrationTest {
    @Test
    fun `legacy schema requires opt-in baseline and preserves existing rows`() {
        DriverManager.getConnection(postgres.jdbcUrl, postgres.username, postgres.password).use { connection ->
            connection.createStatement().use {
                it.execute("""CREATE TABLE applications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company_name VARCHAR(255) NOT NULL, job_title VARCHAR(255) NOT NULL,
                    application_date DATE NOT NULL, status VARCHAR(255) NOT NULL,
                    job_listing_url VARCHAR(255), notes TEXT)""")
                it.execute("INSERT INTO applications (company_name,job_title,application_date,status) VALUES ('Existing Demo','Backend','2026-10-18','SENT')")
            }
        }
        val config = Flyway.configure().dataSource(postgres.jdbcUrl, postgres.username, postgres.password)
        assertThatThrownBy { config.load().migrate() }.hasMessageContaining("non-empty schema")
        val flyway = config.baselineOnMigrate(true).baselineVersion("0").load()
        assertThat(flyway.migrate().migrationsExecuted).isEqualTo(1)
        assertThat(flyway.migrate().migrationsExecuted).isZero()
        DriverManager.getConnection(postgres.jdbcUrl, postgres.username, postgres.password).use { connection ->
            connection.createStatement().executeQuery("SELECT company_name FROM applications").use {
                assertThat(it.next()).isTrue()
                assertThat(it.getString(1)).isEqualTo("Existing Demo")
                assertThat(it.next()).isFalse()
            }
        }
    }

    companion object {
        @Container @JvmField val postgres = PostgreSQLContainer<Nothing>("postgres:17-alpine")
    }
}
